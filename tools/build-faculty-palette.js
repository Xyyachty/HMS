/*
 * Generates public/css/faculty-palette.css.
 *
 * public/css/app.css is a frozen Tailwind build (no tailwindcss installed here) still
 * carrying Tailwind's stock hues. The Faculty layout loads it as-is, so this script
 * reads every colour utility out of that build and re-emits it with the colour swapped
 * for the four-colour system the Student and Dean portals use — wine, gold, cream, ink.
 * Same class names, same layout; only the colour value changes.
 *
 * Run after either palette changes:   node tools/build-faculty-palette.js
 * It asserts its own output at the end, so a bad run fails loudly.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'public/css/app.css');
const OUT = path.join(ROOT, 'public/css/faculty-palette.css');

// The four colours as full shade scales. The values the Student config already
// spells out are kept exactly; the gaps (300, 800, 900) are filled in to match.
const wine  = { 50:'#FBEAEE',100:'#F6D5DC',200:'#ECAFBE',300:'#DE8299',400:'#C4425E',500:'#9E1B3C',600:'#7B1730',700:'#5E1024',800:'#4A0D1C',900:'#2A1118' };
const gold  = { 50:'#FBF3E0',100:'#F2E3BE',200:'#E9D3A0',300:'#E0C283',400:'#D9B86A',500:'#C9A45C',600:'#B8873C',700:'#96692C',800:'#7A5322',900:'#5C3E19' };
const ink   = { 50:'#FAF6F5',100:'#F2E9E7',200:'#E4D3CF',300:'#C9AFAA',400:'#7A6068',500:'#6B4A54',600:'#5A3941',700:'#47262D',800:'#341620',900:'#2A1118' };

const families = {};
for (const f of ['red','rose','pink','fuchsia','purple','violet','indigo','blue','sky','cyan','teal']) families[f] = wine;
for (const f of ['amber','yellow','orange','emerald','green','lime']) families[f] = gold;
for (const f of ['slate','gray','zinc','neutral','stone']) families[f] = ink;

const named = {
  'brand': '#7B1730', 'brand-light': '#C9A45C', 'brand-dark': '#4A0D1C', 'brand-soft': '#FBEEE9',
  'rose-accent': '#C4425E', 'plum-accent': '#C9A45C', 'plum-soft': '#FBEEE9', 'amber-soft': '#FBF3E0',
};

// Split "a{b}c{d}" at the current brace depth into [selector, body] pairs.
function parse(src) {
  const out = [];
  let i = 0;
  while (i < src.length) {
    const open = src.indexOf('{', i);
    if (open < 0) break;
    let depth = 1, j = open + 1;
    while (j < src.length && depth) { const c = src[j++]; if (c === '{') depth++; else if (c === '}') depth--; }
    out.push([src.slice(i, open).trim(), src.slice(open + 1, j - 1)]);
    i = j;
  }
  return out;
}

const UTIL = /\.((?:[\w-]+\\:)*)(bg|text|border|ring|from|via|to|fill|stroke|divide|shadow|outline|placeholder|accent|decoration|caret)-((?:[a-z]+-\d{2,3})|brand(?:-[a-z]+)?|rose-accent|plum-[a-z]+|amber-soft)(?:\\\/[\d.]+)?(?![\w-])/;

function newColor(name) {
  if (named[name]) return named[name];
  const m = name.match(/^([a-z]+)-(\d+)$/);
  return m && families[m[1]] ? families[m[1]][m[2]] : null;
}

const toRgb = h => [1, 3, 5].map(k => parseInt(h.slice(k, k + 2), 16));

// Rewrite every colour in a declaration body to one colour, keeping the shape
// Tailwind emitted (rgb(r g b/var(--tw-…)), rgba(r,g,b,.2), #hex) intact.
function recolor(body, hex) {
  const [r, g, b] = toRgb(hex);
  return body
    .replace(/(rgba?)\(\s*\d+(\s*,\s*|\s+)\d+(\s*,\s*|\s+)\d+/g, (_, fn, s1, s2) => `${fn}(${r}${s1}${g}${s2}${b}`)
    .replace(/#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b/g, hex.toLowerCase());
}

function rules(list) {
  let out = '';
  for (const [sel, body] of list) {
    if (sel.startsWith('@')) {
      if (/^@(media|supports)/.test(sel)) {
        const inner = rules(parse(body));
        if (inner) out += `${sel}{${inner}}\n`;
      }
      continue;
    }
    const m = sel.match(UTIL);
    if (!m) continue;
    const hex = newColor(m[3]);
    if (!hex) continue;
    if (!/rgba?\(|#[0-9a-fA-F]{3}/.test(body)) continue;
    out += `${sel}{${recolor(body, hex)}}\n`;
  }
  return out;
}

const header = `/* Faculty palette override — GENERATED by tools/build-faculty-palette.js, do not hand-edit.
 *
 * Loaded straight after the frozen public/css/app.css build, so every colour utility in
 * that build resolves to the Student portal's four colours: wine, gold, cream and ink.
 */
*,:after,:before{--tw-ring-color:rgba(158,27,60,.5)}
::backdrop{--tw-ring-color:rgba(158,27,60,.5)}
`;

const css = rules(parse(fs.readFileSync(SRC, 'utf8')));
fs.writeFileSync(OUT, header + css);

// ── Self-check: the output must be balanced and hold nothing but the four colours ──
const assert = require('assert');
const written = fs.readFileSync(OUT, 'utf8');

let depth = 0;
for (const c of written) {
  if (c === '{') depth++;
  else if (c === '}') { depth--; assert.ok(depth >= 0, 'unbalanced braces in generated CSS'); }
}
assert.strictEqual(depth, 0, 'unbalanced braces in generated CSS');

const allowed = new Set(
  [...Object.values(wine), ...Object.values(gold), ...Object.values(ink), ...Object.values(named)]
    .map(h => h.slice(1).toLowerCase())
    .concat(['fff', '0000'])
);
for (const m of written.matchAll(/#([0-9a-fA-F]{3,6})\b/g)) {
  assert.ok(allowed.has(m[1].toLowerCase()), `off-palette hex #${m[1]} in generated CSS`);
}
for (const m of written.matchAll(/rgba?\(\s*(\d+)[ ,]+(\d+)[ ,]+(\d+)/g)) {
  const hex = [m[1], m[2], m[3]].map(n => (+n).toString(16).padStart(2, '0')).join('');
  assert.ok(allowed.has(hex), `off-palette rgb #${hex} in generated CSS`);
}

console.log(`faculty-palette.css: ${css.split('\n').length - 1} rules, palette clean`);
